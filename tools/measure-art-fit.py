#!/usr/bin/env python3
"""Measure the visible object in every Coast Camp board sprite and write v5/next/art-bounds.mjs.

Build 45i (board art consistency pass). The painted icons were cut so the object fills about 91 %
of its canvas on its longest side (the four first Rover parts about 95 %), whatever the object is,
so a copper offcut and an excavator are the same size unless the board scales them. This measures
each sprite's solid object (alpha >= 160: faint baked shadows and glows do not count) and records
its longest side, its short/long ratio and its centre, as shares of the canvas. The game turns that
into a per-sprite fit (v5/next/art-fit.mjs reads art-bounds.mjs). Run after adding or replacing board art:

    python3 tools/measure-art-fit.py
"""
import glob, json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, 'v5/assets/premium/coast/icons')
KEEP = ['copper-offcut', 'grip-tool', 'split-spanner', 'pocket-winch']  # chains.mjs KEEP, the -vibrant files
files = {os.path.basename(f)[:-5]: f for f in sorted(glob.glob(os.path.join(ICONS, '*.webp')))}
files.update({k: os.path.join(ROOT, f'v5/assets/premium/{k}-vibrant.webp') for k in KEEP})

bounds = {}
for name, path in sorted(files.items()):
    im = Image.open(path).convert('RGBA'); w, h = im.size
    box = im.getchannel('A').point(lambda v: 255 if v >= 160 else 0).getbbox()
    if not box: continue
    bw, bh = (box[2] - box[0]) / w, (box[3] - box[1]) / h
    bounds[name] = [round(max(bw, bh), 3), round(min(bw, bh) / max(bw, bh), 3),
                    round((box[0] + box[2]) / 2 / w, 3), round((box[1] + box[3]) / 2 / h, 3)]

body = ',\n'.join(f" '{k}':{json.dumps(v)}" for k, v in bounds.items())
out = f"""// Generated by tools/measure-art-fit.py — do not edit by hand; re-run it after changing board art.
// Each board sprite's solid object (alpha >= 160) as shares of its canvas:
// [longest side, short/long ratio, centre x, centre y].
export const ART_BOUNDS={{
{body}
}};
"""
open(os.path.join(ROOT, 'v5/next/art-bounds.mjs'), 'w').write(out)
print(f'wrote v5/next/art-bounds.mjs ({len(bounds)} sprites)')
